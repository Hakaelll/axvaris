const { chromium } = require(process.env.AXVARIS_PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({headless:true,channel:"msedge"});
  const page = await browser.newPage({viewport:{width:1440,height:900}, reducedMotion:'reduce'});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://127.0.0.1:1420');
  await page.waitForTimeout(1800); await page.getByRole('combobox',{name:'Capture mode',exact:true}).selectOption('demo'); await page.waitForTimeout(5500); await page.evaluate(()=>document.fonts.ready);
  console.log((await page.locator('body').innerText()).slice(0,1600));
  fs.mkdirSync('docs/images',{recursive:true});
  await page.screenshot({path:'docs/images/axvaris-today.png'});
  await page.getByRole('button',{name:'Live',exact:true}).first().click();
  await page.waitForTimeout(900);
  await page.screenshot({path:'docs/images/axvaris-live.png'});
  await page.setViewportSize({width:720,height:600});
  await page.screenshot({path:'docs/images/axvaris-compact.png'});
  await page.getByRole('button',{name:'Data & Health',exact:true}).first().click();
  await page.waitForTimeout(700);
  await page.screenshot({path:'docs/images/axvaris-dns.png'});
  console.log(JSON.stringify({errors,overflow:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)}));
  await browser.close();
})().catch(error=>{console.error(error);process.exitCode=1});
